#!/usr/bin/env python3
"""Build a bootable Pocket8086 CP/M 2.2 card image.

    python tools/build.py --sectors 7872            # size of the target card
    python tools/build.py --sectors 7872 --files cpmfiles

Produces build/cpm.img (exactly --sectors * 512 bytes, or less with --trim).

Card layout (512-byte sectors):
    LBA 0          boot sector (stage 1) + partition table (type 52h = CP/M)
    LBA 1..63      native loader + CCP/BDOS + 8080 BIOS
    LBA 64..       CP/M drives A:, B:, ... (up to 8 MB each)

Each CP/M drive: 64 logical 128-byte sectors per track (= 16 card sectors),
no system tracks, 2K blocks (<= 4 MB) or 4K blocks (> 4 MB).
"""
import argparse
import os
import subprocess
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import cpmfs  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'src')
BUILD = os.path.join(ROOT, 'build')
TOOLS = os.path.join(ROOT, 'tools')
NASM = os.environ.get('NASM') or next(
    (p for p in (os.path.join(TOOLS, 'nasm-2.16.03', 'nasm.exe'),) if os.path.isfile(p)),
    'nasm')                     # else: nasm on the PATH

RESERVED = 64           # sectors before drive A:
SPT = 64                # CP/M logical sectors per track
HOST_PER_TRACK = SPT * 128 // 512
MAX_DRIVE = 16384       # sectors (8 MB, the CP/M 2.2 limit)
MIN_DRIVE = 1024        # sectors (512 KB) - keeps DSM > 255
BIOS_LIMIT = 0xFE00     # ESEG:FE00-FFFF is the native stack


def plan_drives(total, maxdrives):
    avail = total - RESERVED
    drives = []
    lba = RESERVED
    while avail >= MIN_DRIVE and len(drives) < maxdrives:
        size = min(avail, MAX_DRIVE)
        size -= size % HOST_PER_TRACK
        bls = 4096 if size > 8192 else 2048
        blocks = size * 512 // bls
        d = dict(base=lba, sectors=size, tracks=size // HOST_PER_TRACK, bls=bls,
                 dsm=blocks - 1)
        d['bsh'] = {2048: 4, 4096: 5}[bls]
        d['blm'] = bls // 128 - 1
        d['exm'] = {2048: 0, 4096: 1}[bls]
        d['drm'] = (4 * bls) // 32 - 1           # directory = 4 blocks
        d['al0'] = 0xF0
        drives.append(d)
        lba += size
        avail -= size
    if not drives:
        sys.exit('card too small: need at least %d sectors' % (RESERVED + MIN_DRIVE))
    return drives


def gen_includes(drives):
    n = len(drives)
    L = ['; generated by build.py - do not edit', 'NDISKS\tEQU\t%d' % n, 'DPBASE:']
    for i in range(n):
        L.append('\tDW\t0,0,0,0,DIRBUF,DPB%d,CSV%d,ALV%d' % (i, i, i))
    for i, d in enumerate(drives):
        L.append('DPB%d:\tDW\t%d\t;SPT  drive %s: %d KB, %d-byte blocks' %
                 (i, SPT, chr(65 + i), d['sectors'] // 2, d['bls']))
        L.append('\tDB\t%d,%d,%d\t;BSH,BLM,EXM' % (d['bsh'], d['blm'], d['exm']))
        L.append('\tDW\t%d,%d\t;DSM,DRM' % (d['dsm'], d['drm']))
        L.append('\tDB\t0%02XH,0\t;AL0,AL1' % d['al0'])
        L.append('\tDW\t0,0\t;CKS (fixed disk), OFF')
    L.append('DIRBUF:\tDS\t128')
    for i, d in enumerate(drives):
        L.append('ALV%d:\tDS\t%d' % (i, d['dsm'] // 8 + 1))
        L.append('CSV%d:\tDS\t0' % i)
    with open(os.path.join(BUILD, 'disks.inc'), 'w') as f:
        f.write('\n'.join(L) + '\n')

    names = 'A:' if n == 1 else 'A:-%s:' % chr(64 + n)
    sizes = ', '.join('%s: %d KB' % (chr(65 + i), d['sectors'] // 2)
                      for i, d in enumerate(drives))
    N = ['; generated by build.py - do not edit',
         'NDISKS equ %d' % n, 'SPT equ %d' % SPT,
         '%%define DRIVES_MSG "Drives %s (%s)"' % (names, sizes),
         '%macro DRIVE_TABLES 0',
         'drv_base:   dd ' + ', '.join(str(d['base']) for d in drives),
         'drv_tracks: dw ' + ', '.join(str(d['tracks']) for d in drives),
         '%endmacro']
    with open(os.path.join(BUILD, 'layout.inc'), 'w') as f:
        f.write('\n'.join(N) + '\n')


def run(cmd):
    print('  ' + ' '.join(os.path.basename(c) if i == 0 else c for i, c in enumerate(cmd)))
    r = subprocess.run(cmd, capture_output=True, text=True)
    if r.stdout.strip():
        print('    ' + r.stdout.strip().replace('\n', '\n    '))
    if r.returncode:
        sys.exit(r.stderr)


def read_sym(path):
    syms = {}
    with open(path) as f:
        for line in f:
            v, k = line.split()
            syms[k] = int(v, 16)
    return syms


def write_files(img, d, files):
    """Write host files onto CP/M drive d (dict from plan_drives) inside img."""
    region = bytearray(img[d['base'] * 512:(d['base'] + d['sectors']) * 512])
    drv = cpmfs.CpmDrive(region, d)
    for path in files:
        data = open(path, 'rb').read()
        if cpmfs.is_text_name(path):
            data = cpmfs.to_cpm_text(data)
        try:
            drv.write(os.path.basename(path), data)
        except cpmfs.CpmError as e:
            sys.exit('%s: %s' % (path, e))
    img[d['base'] * 512:(d['base'] + d['sectors']) * 512] = region
    return len(drv.files()), (d['dsm'] + 1) - len(drv.free_blocks())


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--sectors', type=int, required=True,
                    help='card size in 512-byte sectors')
    ap.add_argument('--files', default=os.path.join(ROOT, 'cpmfiles'),
                    help='folder whose files go onto drive A:')
    ap.add_argument('--drives', type=int, default=4, help='max CP/M drives (1-16)')
    ap.add_argument('--out', default=os.path.join(BUILD, 'cpm.img'))
    a = ap.parse_args()
    os.makedirs(BUILD, exist_ok=True)

    drives = plan_drives(a.sectors, max(1, min(16, a.drives)))
    print('Card: %d sectors (%.1f MB)' % (a.sectors, a.sectors / 2048))
    for i, d in enumerate(drives):
        print('  %s: LBA %d-%d, %d KB, %d tracks, BLS %d, DSM %d, DRM %d' % (
            chr(65 + i), d['base'], d['base'] + d['sectors'] - 1, d['sectors'] // 2,
            d['tracks'], d['bls'], d['dsm'], d['drm']))
    gen_includes(drives)

    asm = [sys.executable, os.path.join(TOOLS, 'asm8080.py')]
    run(asm + [os.path.join(SRC, 'cpm22.asm'), os.path.join(BUILD, 'cpm22.bin'),
               '--sym', os.path.join(BUILD, 'cpm22.sym')])
    run(asm + [os.path.join(SRC, 'bios.asm'), os.path.join(BUILD, 'bios.bin'),
               '--sym', os.path.join(BUILD, 'bios.sym')])
    bsym = read_sym(os.path.join(BUILD, 'bios.sym'))
    if bsym['BIOSEND'] > BIOS_LIMIT:
        sys.exit('BIOS ends at %04X, past %04X' % (bsym['BIOSEND'], BIOS_LIMIT))
    print('  BIOS F600H-%04XH, native stack FE00H-FFFFH' % (bsym['BIOSEND'] - 1))

    run([NASM, '-f', 'bin', '-I', BUILD + os.sep, '-o', os.path.join(BUILD, 'loader.bin'),
         '-l', os.path.join(BUILD, 'loader.lst'), os.path.join(SRC, 'loader.asm')])
    loader = open(os.path.join(BUILD, 'loader.bin'), 'rb').read()
    nsec = (len(loader) + 511) // 512
    if nsec > RESERVED - 1:
        sys.exit('loader too big')
    run([NASM, '-f', 'bin', '-DLOADER_SECTORS=%d' % nsec, '-o',
         os.path.join(BUILD, 'boot.bin'), os.path.join(SRC, 'boot.asm')])
    boot = bytearray(open(os.path.join(BUILD, 'boot.bin'), 'rb').read())
    assert len(boot) == 512

    # partition table: one entry covering the CP/M drives, type 52h
    first = drives[0]['base']
    count = drives[-1]['base'] + drives[-1]['sectors'] - first
    pe = bytes([0x00, 0xFE, 0xFF, 0xFF, 0x52, 0xFE, 0xFF, 0xFF])
    pe += first.to_bytes(4, 'little') + count.to_bytes(4, 'little')
    boot[0x1BE:0x1CE] = pe

    end = drives[-1]['base'] + drives[-1]['sectors']
    img = bytearray(b'\xe5' * (end * 512))
    img[0:RESERVED * 512] = bytes(RESERVED * 512)
    img[0:512] = boot
    img[512:512 + len(loader)] = loader

    files = []
    if a.files and os.path.isdir(a.files):
        files = sorted(os.path.join(a.files, f) for f in os.listdir(a.files)
                       if os.path.isfile(os.path.join(a.files, f)))
    nent, used = write_files(img, drives[0], files)
    print('  A: %d files, %d of %d blocks used' % (nent, used, drives[0]['dsm'] + 1))

    with open(a.out, 'wb') as f:
        f.write(img)
    print('Wrote %s (%d sectors, loader %d sectors)' % (a.out, len(img) // 512, nsec))


if __name__ == '__main__':
    main()
