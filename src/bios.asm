;**************************************************************
;*
;*   CP/M 2.2 BIOS for the Pocket8086 with an NEC V30 (or V20)
;*
;*   This BIOS runs in the V30's 8080 emulation mode.  Every
;*   hardware-related function is a CALLN (ED ED nn) into a
;*   native-mode x86 handler in LOADER.ASM, which uses the PC
;*   BIOS (INT 10h/13h/14h/16h/17h).
;*
;*   8080 register  <->  x86 register while in a CALLN handler:
;*       A=AL  B=CH  C=CL  D=DH  E=DL  H=BH  L=BL  SP=BP
;*
;**************************************************************
;
MSIZE	EQU	63		;'63K' layout
CCP	EQU	(MSIZE-7)*1024	;E000H
BDOS	EQU	CCP+806H	;BDOS entry point
BIOS	EQU	CCP+1600H	;F600H
IOBYTE	EQU	0003H
TDRIVE	EQU	0004H		;current user (high nibble) / drive
;
;   CALLN vector numbers (must match LOADER.ASM)
;
VBASE	EQU	0E0H
VWBOOT	EQU	VBASE+1
VCONST	EQU	VBASE+2
VCONIN	EQU	VBASE+3
VCONOUT	EQU	VBASE+4
VLIST	EQU	VBASE+5
VPUNCH	EQU	VBASE+6
VREADER	EQU	VBASE+7
VHOME	EQU	VBASE+8
VSELDSK	EQU	VBASE+9
VSETTRK	EQU	VBASE+10
VSETSEC	EQU	VBASE+11
VSETDMA	EQU	VBASE+12
VREAD	EQU	VBASE+13
VWRITE	EQU	VBASE+14
VLISTST	EQU	VBASE+15
;
	ORG	BIOS
;
;   Standard BIOS jump vector
;
	JMP	BOOT
WBOOTE	JMP	WBOOT
	JMP	CONST
	JMP	CONIN
	JMP	CONOUT
	JMP	LIST
	JMP	PUNCH
	JMP	READER
	JMP	HOME
	JMP	SELDSK
	JMP	SETTRK
	JMP	SETSEC
	JMP	SETDMA
	JMP	READ
	JMP	WRITE
	JMP	LISTST
	JMP	SECTRAN
;
;   Cold start.  The native loader has already copied the CCP and
; BDOS into place and printed the sign-on message.
;
BOOT	LXI	SP,80H
	XRA	A
	STA	IOBYTE
	STA	TDRIVE		;drive A:, user 0
	JMP	GOCPM
;
;   Warm start: the native side reloads a fresh CCP+BDOS from the
; copy it keeps in conventional memory (no disk access needed).
;
WBOOT	LXI	SP,80H
	CALLN	VWBOOT
;
GOCPM	MVI	A,0C3H		;JMP opcode
	STA	0000H
	LXI	H,WBOOTE
	SHLD	0001H		;JMP WBOOT at 0000H
	STA	0005H
	LXI	H,BDOS
	SHLD	0006H		;JMP BDOS at 0005H
	LXI	B,0080H
	CALL	SETDMA
	LDA	TDRIVE
	ANI	0FH
	CPI	NDISKS		;drive still valid?
	JC	GOCPM1
	LDA	TDRIVE
	ANI	0F0H		;no, keep user number, use drive A:
	STA	TDRIVE
GOCPM1	LDA	TDRIVE
	MOV	C,A
	JMP	CCP		;go to the command processor
;
;   Character I/O: straight through to native code.
;
CONST	CALLN	VCONST
	RET
CONIN	CALLN	VCONIN
	RET
CONOUT	CALLN	VCONOUT
	RET
LIST	CALLN	VLIST
	RET
PUNCH	CALLN	VPUNCH
	RET
READER	CALLN	VREADER
	RET
LISTST	CALLN	VLISTST
	RET
;
;   Disk I/O
;
HOME	CALLN	VHOME
	RET
;
SELDSK	LXI	H,0		;HL=0 means 'no such drive'
	MOV	A,C
	CPI	NDISKS
	RNC
	CALLN	VSELDSK		;tell native code which drive
	MOV	L,C
	MVI	H,0
	DAD	H		;*2
	DAD	H		;*4
	DAD	H		;*8
	DAD	H		;*16
	LXI	D,DPBASE
	DAD	D		;HL = address of disk parameter header
	RET
;
SETTRK	CALLN	VSETTRK
	RET
SETSEC	CALLN	VSETSEC
	RET
SETDMA	CALLN	VSETDMA
	RET
READ	CALLN	VREAD		;returns A=0 ok, A=1 error
	RET
WRITE	CALLN	VWRITE
	RET
;
;   No sector skew on a flash card.
;
SECTRAN	MOV	H,B
	MOV	L,C
	RET
;
;   Disk parameter headers/blocks and buffers (generated by build.py)
;
	INCLUDE	../build/disks.inc
;
BIOSEND	EQU	$
	END
